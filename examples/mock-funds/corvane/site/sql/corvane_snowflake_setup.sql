-- Corvane Equity Partners (fictional): one-time Snowflake setup. NOT run by any test: it is
-- Snowflake-only SQL (storage integration, external tables, row access policy) that DuckDB cannot
-- run. corvane_views.sql builds on the objects created here.

USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS CORVANE;
CREATE SCHEMA IF NOT EXISTS CORVANE.CURATED;
CREATE SCHEMA IF NOT EXISTS CORVANE.REF;
CREATE SCHEMA IF NOT EXISTS CORVANE.SERVING;

-- The S3 curated/ prefix, read through an IAM role Snowflake assumes (no keys stored).
CREATE STORAGE INTEGRATION IF NOT EXISTS CORVANE_S3
  TYPE = EXTERNAL_STAGE STORAGE_PROVIDER = 'S3' ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::111122223333:role/corvane-snowflake-reader'
  STORAGE_ALLOWED_LOCATIONS = ('s3://corvane-curated/curated/');
CREATE STAGE IF NOT EXISTS CORVANE.CURATED.LAKE_STAGE
  URL = 's3://corvane-curated/curated/' STORAGE_INTEGRATION = CORVANE_S3
  FILE_FORMAT = (TYPE = PARQUET);

-- External tables over the Hive layout dt=YYYY-MM-DD/. DT is read from the file path, because
-- Parquet files hold no partition column. Column names are upper case, as everything here is.
CREATE OR REPLACE EXTERNAL TABLE CORVANE.CURATED.PRICES_DAILY_EXT (
  DT DATE AS TO_DATE(SPLIT_PART(SPLIT_PART(METADATA$FILENAME, 'dt=', 2), '/', 1)),
  SECURITY_ID VARCHAR AS (VALUE:security_id::VARCHAR),
  CLOSE_LOCAL DOUBLE AS (VALUE:close_local::DOUBLE),
  TOTAL_RETURN_LOCAL DOUBLE AS (VALUE:total_return_local::DOUBLE),
  VOLUME NUMBER AS (VALUE:volume::NUMBER)
) PARTITION BY (DT) LOCATION = @CORVANE.CURATED.LAKE_STAGE/prices_daily/
  AUTO_REFRESH = TRUE FILE_FORMAT = (TYPE = PARQUET);
CREATE OR REPLACE EXTERNAL TABLE CORVANE.CURATED.FX_DAILY_EXT (
  DT DATE AS TO_DATE(SPLIT_PART(SPLIT_PART(METADATA$FILENAME, 'dt=', 2), '/', 1)),
  CURRENCY VARCHAR AS (VALUE:currency::VARCHAR),
  USD_PER_UNIT DOUBLE AS (VALUE:usd_per_unit::DOUBLE)
) PARTITION BY (DT) LOCATION = @CORVANE.CURATED.LAKE_STAGE/fx_daily/ FILE_FORMAT = (TYPE = PARQUET);
CREATE OR REPLACE EXTERNAL TABLE CORVANE.CURATED.FACTOR_SCORES_EXT (
  DT DATE AS TO_DATE(SPLIT_PART(SPLIT_PART(METADATA$FILENAME, 'dt=', 2), '/', 1)),
  SECURITY_ID VARCHAR AS (VALUE:security_id::VARCHAR),
  FACTOR_ID VARCHAR AS (VALUE:factor_id::VARCHAR),
  SCORE DOUBLE AS (VALUE:score::DOUBLE),
  AS_OF VARCHAR AS (VALUE:as_of::VARCHAR)
) PARTITION BY (DT) LOCATION = @CORVANE.CURATED.LAKE_STAGE/factor_scores/
  FILE_FORMAT = (TYPE = PARQUET);

-- Native tables: holdings, benchmark, books, reference. Loaded by COPY INTO from the load stage
-- (the stand-in's snowflake_stage/ folder), so these are the columns the Parquet files carry.
CREATE TABLE IF NOT EXISTS CORVANE.CURATED.SECURITY_MASTER (SECURITY_ID VARCHAR, NAME VARCHAR,
  SECTOR VARCHAR, INDUSTRY VARCHAR, COUNTRY VARCHAR, CURRENCY VARCHAR, MCAP_USD DOUBLE);
CREATE TABLE IF NOT EXISTS CORVANE.CURATED.BENCH_WEIGHTS (AS_OF_DATE DATE, BENCHMARK_ID VARCHAR,
  SECURITY_ID VARCHAR, WEIGHT DOUBLE);
CREATE TABLE IF NOT EXISTS CORVANE.CURATED.BENCH_RETURNS (DATE DATE, BENCHMARK_ID VARCHAR,
  TOTAL_RETURN_USD DOUBLE);
CREATE TABLE IF NOT EXISTS CORVANE.CURATED.HOLDINGS_DAILY (AS_OF_DATE DATE, ACCOUNT_ID VARCHAR,
  SECURITY_ID VARCHAR, SHARES DOUBLE);
CREATE TABLE IF NOT EXISTS CORVANE.REF.ACCOUNTS (ACCOUNT_ID VARCHAR, NAME VARCHAR,
  STRATEGY VARCHAR, BENCHMARK_ID VARCHAR, CLIENT VARCHAR, AUM_USD DOUBLE);
CREATE TABLE IF NOT EXISTS CORVANE.REF.MANDATE_RESTRICTIONS (ACCOUNT_ID VARCHAR,
  RULE_TYPE VARCHAR, RULE_VALUE VARCHAR);

-- Who may read what, in Snowflake. One reader role per team, granted to people through the
-- identity provider's SCIM groups.
CREATE ROLE IF NOT EXISTS CORVANE_PM_US_CORE_READER;
CREATE ROLE IF NOT EXISTS CORVANE_PM_GLOBAL_QUALITY_READER;
CREATE ROLE IF NOT EXISTS CORVANE_RISK_READER;
CREATE ROLE IF NOT EXISTS CORVANE_CLIENT_SERVICE_READER;
CREATE ROLE IF NOT EXISTS CORVANE_PLATFORM_READER;   -- the one role the server connects with
GRANT USAGE ON DATABASE CORVANE TO ROLE CORVANE_PLATFORM_READER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CORVANE TO ROLE CORVANE_PLATFORM_READER;
GRANT SELECT ON ALL TABLES IN DATABASE CORVANE TO ROLE CORVANE_PLATFORM_READER;
GRANT SELECT ON ALL VIEWS IN DATABASE CORVANE TO ROLE CORVANE_PLATFORM_READER;

-- Row access: a team sees holdings only of its accounts. This is Snowflake's own control and sees
-- the session's role, which for the platform is always CORVANE_PLATFORM_READER: it cannot see
-- the person calling the tool, so access.toml remains the only per-caller gate.
CREATE OR REPLACE ROW ACCESS POLICY CORVANE.CURATED.RAP_HOLDINGS AS (ACCOUNT_ID VARCHAR)
RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('CORVANE_RISK_READER', 'CORVANE_PLATFORM_READER')
  OR (CURRENT_ROLE() = 'CORVANE_PM_US_CORE_READER' AND ACCOUNT_ID IN ('LCC', 'SMA_PEN_A', 'SMA_FND_B'))
  OR (CURRENT_ROLE() = 'CORVANE_PM_GLOBAL_QUALITY_READER' AND ACCOUNT_ID IN ('GQ', 'SMA_SWF_C'));
ALTER TABLE CORVANE.CURATED.HOLDINGS_DAILY ADD ROW ACCESS POLICY CORVANE.CURATED.RAP_HOLDINGS
  ON (ACCOUNT_ID);
