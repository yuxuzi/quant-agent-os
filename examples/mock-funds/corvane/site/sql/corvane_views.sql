-- Corvane Equity Partners (fictional): the serving views the dataset store reads.
--
-- Written in the portable subset of Snowflake SQL that DuckDB also runs, so the same text builds
-- the views in Snowflake (CORVANE.SERVING) and in the offline stand-in the tests use. Statements
-- are separated by a line holding only "--;". The *_EXT objects are Snowflake external tables over
-- the S3 curated/ prefix in production (see corvane_snowflake_setup.sql); offline they are views
-- over the Parquet files. DT is the Hive partition column, a DATE.
--
-- Conventions the views fix, so every tool reads the same numbers:
--   * A security's USD return on a day is (1 + local return) * (1 + FX return) - 1. On a day its
--     market was shut (no price row) the local return is 0, so only the currency moves.
--   * Holdings are valued at the last close on or before the day, converted at that day's FX.
--   * Benchmark weights are the vendor's month-start weights, drifted by USD returns, and a name
--     that stops trading leaves the benchmark at the end of its last day, the rest renormalised.
--   * A factor score is used from the day its file was delivered (DT), not from its as-of date.

CREATE SCHEMA IF NOT EXISTS CORVANE.SERVING
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_CAL AS
SELECT DISTINCT DT FROM CORVANE.CURATED.FX_DAILY_EXT
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_LIFE AS
SELECT p.SECURITY_ID, m.CURRENCY, MIN(p.DT) AS FIRST_DT, MAX(p.DT) AS LAST_DT
FROM CORVANE.CURATED.PRICES_DAILY_EXT p
JOIN CORVANE.CURATED.SECURITY_MASTER m ON m.SECURITY_ID = p.SECURITY_ID
GROUP BY p.SECURITY_ID, m.CURRENCY
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_FX_RET AS
SELECT DT, CURRENCY,
       USD_PER_UNIT / LAG(USD_PER_UNIT) OVER (PARTITION BY CURRENCY ORDER BY DT) - 1.0 AS FX_RET
FROM CORVANE.CURATED.FX_DAILY_EXT
UNION ALL
SELECT DT, 'USD', 0.0 FROM CORVANE.SERVING.V_CAL
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_RET_USD AS
SELECT c.DT, l.SECURITY_ID,
       (1.0 + COALESCE(p.TOTAL_RETURN_LOCAL, 0.0)) * (1.0 + COALESCE(f.FX_RET, 0.0)) - 1.0 AS RET_USD
FROM CORVANE.SERVING.V_CAL c
JOIN CORVANE.SERVING.V_LIFE l ON c.DT > l.FIRST_DT AND c.DT <= l.LAST_DT
LEFT JOIN CORVANE.CURATED.PRICES_DAILY_EXT p ON p.SECURITY_ID = l.SECURITY_ID AND p.DT = c.DT
LEFT JOIN CORVANE.SERVING.V_FX_RET f ON f.CURRENCY = l.CURRENCY AND f.DT = c.DT
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_CLOSE_CARRIED AS
WITH j AS (
  SELECT c.DT, l.SECURITY_ID, l.CURRENCY,
         MAX(p.DT) OVER (PARTITION BY l.SECURITY_ID ORDER BY c.DT) AS PRICE_DT
  FROM CORVANE.SERVING.V_CAL c
  JOIN CORVANE.SERVING.V_LIFE l ON c.DT >= l.FIRST_DT AND c.DT <= l.LAST_DT
  LEFT JOIN CORVANE.CURATED.PRICES_DAILY_EXT p ON p.SECURITY_ID = l.SECURITY_ID AND p.DT = c.DT
)
SELECT j.DT, j.SECURITY_ID, j.CURRENCY, q.CLOSE_LOCAL
FROM j
JOIN CORVANE.CURATED.PRICES_DAILY_EXT q ON q.SECURITY_ID = j.SECURITY_ID AND q.DT = j.PRICE_DT
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_WEIGHTS_DAILY AS
WITH v AS (
  SELECT h.AS_OF_DATE AS DT, h.ACCOUNT_ID, h.SECURITY_ID,
         CASE WHEN h.SECURITY_ID = 'CASH_USD' THEN h.SHARES
              ELSE h.SHARES * k.CLOSE_LOCAL * COALESCE(fx.USD_PER_UNIT, 1.0) END AS VALUE_USD
  FROM CORVANE.CURATED.HOLDINGS_DAILY h
  LEFT JOIN CORVANE.SERVING.V_CLOSE_CARRIED k
    ON k.DT = h.AS_OF_DATE AND k.SECURITY_ID = h.SECURITY_ID
  LEFT JOIN CORVANE.CURATED.FX_DAILY_EXT fx ON fx.DT = h.AS_OF_DATE AND fx.CURRENCY = k.CURRENCY
)
SELECT DT, ACCOUNT_ID, SECURITY_ID,
       VALUE_USD / SUM(VALUE_USD) OVER (PARTITION BY DT, ACCOUNT_ID) AS WEIGHT
FROM v
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_BENCH_W_DAILY AS
WITH cal AS (
  SELECT c.DT, b.BENCHMARK_ID, MAX(b.AS_OF_DATE) AS REB_DT
  FROM CORVANE.SERVING.V_CAL c
  JOIN (SELECT DISTINCT AS_OF_DATE, BENCHMARK_ID FROM CORVANE.CURATED.BENCH_WEIGHTS) b
    ON b.AS_OF_DATE <= c.DT
  GROUP BY c.DT, b.BENCHMARK_ID
), grown AS (
  SELECT cal.DT, cal.BENCHMARK_ID, w.SECURITY_ID,
         w.WEIGHT * EXP(SUM(CASE WHEN cal.DT > cal.REB_DT
                                 THEN LN(1.0 + COALESCE(r.RET_USD, 0.0)) ELSE 0.0 END)
                        OVER (PARTITION BY cal.BENCHMARK_ID, cal.REB_DT, w.SECURITY_ID
                              ORDER BY cal.DT)) AS RAW_W,
         l.LAST_DT
  FROM cal
  JOIN CORVANE.CURATED.BENCH_WEIGHTS w
    ON w.BENCHMARK_ID = cal.BENCHMARK_ID AND w.AS_OF_DATE = cal.REB_DT
  LEFT JOIN CORVANE.SERVING.V_RET_USD r ON r.DT = cal.DT AND r.SECURITY_ID = w.SECURITY_ID
  LEFT JOIN CORVANE.SERVING.V_LIFE l ON l.SECURITY_ID = w.SECURITY_ID
), kept AS (
  SELECT * FROM grown
  WHERE LAST_DT IS NULL OR DT < LAST_DT OR LAST_DT = (SELECT MAX(DT) FROM CORVANE.SERVING.V_CAL)
)
SELECT DT, BENCHMARK_ID, SECURITY_ID,
       RAW_W / SUM(RAW_W) OVER (PARTITION BY DT, BENCHMARK_ID) AS WEIGHT
FROM kept
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_ADV_USD AS
SELECT p.DT, p.SECURITY_ID,
       AVG(p.VOLUME * p.CLOSE_LOCAL * COALESCE(f.USD_PER_UNIT, 1.0))
         OVER (PARTITION BY p.SECURITY_ID ORDER BY p.DT ROWS BETWEEN 19 PRECEDING AND CURRENT ROW)
         AS ADV_USD
FROM CORVANE.CURATED.PRICES_DAILY_EXT p
JOIN CORVANE.SERVING.V_LIFE l ON l.SECURITY_ID = p.SECURITY_ID
LEFT JOIN CORVANE.CURATED.FX_DAILY_EXT f ON f.CURRENCY = l.CURRENCY AND f.DT = p.DT
--;
CREATE OR REPLACE VIEW CORVANE.SERVING.V_SCORES_DAILY AS
WITH s AS (
  SELECT DT AS DELIVERED, SECURITY_ID, FACTOR_ID, SCORE,
         LEAD(DT) OVER (PARTITION BY SECURITY_ID, FACTOR_ID ORDER BY DT) AS NEXT_DT
  FROM CORVANE.CURATED.FACTOR_SCORES_EXT
)
SELECT c.DT, s.SECURITY_ID, s.FACTOR_ID, s.SCORE
FROM CORVANE.SERVING.V_CAL c
JOIN s ON c.DT >= s.DELIVERED AND (s.NEXT_DT IS NULL OR c.DT < s.NEXT_DT)
