"""The tool lock: each served tool's version, permissions, and schemas (decision 0015).

`test_tool_lock.py` fails when a tool's schemas change without the lock being updated, or with
a version bump smaller than the change. After raising the tool's version, run:

    uv run python tests/server/tool_lock.py --update

and add the change to docs/tools-changelog.md.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path
from typing import Any

from quant_agent_os.data import DirectoryDatasetStore
from quant_agent_os.tools import PermissionPolicy, ToolSpec
from quant_agent_os.tools.compatibility import check_lock, lock_entry
from quant_app_factory import AppFactory, PytemplateUvScaffolder
from quant_platform import compose
from quant_research import open_research

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "tool-versions.lock"


def served_tools() -> list[ToolSpec[Any, Any]]:
    """Return every tool the platform can serve, with all three toolsets."""
    with open_research(":memory:") as research, tempfile.TemporaryDirectory() as datasets:
        catalog = compose(
            policy=PermissionPolicy(),
            research=research.research,
            datasets=DirectoryDatasetStore(Path(datasets)),
            factory=AppFactory(PytemplateUvScaffolder()),
        )
    return sorted(catalog.tools, key=lambda spec: spec.name)


def read_lock() -> dict[str, dict[str, Any]]:
    """Return the committed lock, or an empty one before the first update."""
    if not LOCK.exists():
        return {}
    locked: dict[str, dict[str, Any]] = json.loads(LOCK.read_text("utf-8"))["tools"]
    return locked


def render(tools: list[ToolSpec[Any, Any]]) -> str:
    """Return the lock file's text for ``tools``."""
    document = {
        "comment": "Generated by tests/server/tool_lock.py --update; do not edit.",
        "tools": {spec.name: lock_entry(spec) for spec in tools},
    }
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    """Print the lock's problems; with ``--update``, rewrite it unless a bump is too small."""
    tools = served_tools()
    problems = check_lock(read_lock(), tools)
    for problem in problems:
        print(problem)
    if "--update" not in argv:
        return 1 if problems else 0
    blocking = [problem for problem in problems if "version bump" in problem]
    if blocking:
        print("Not updated: raise those tools' versions first.")
        return 1
    LOCK.write_text(render(tools), "utf-8", newline="\n")
    print(f"Wrote {LOCK.relative_to(ROOT)} ({len(tools)} tools).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
